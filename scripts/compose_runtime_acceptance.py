"""Run a disposable Docker Compose runtime acceptance for T3/T6 persistence.

This script creates its own test-only credentials and .env.test file, binds only
127.0.0.1, drives a real ChatGPT-ingress -> WorkBuddy Pull result round trip,
restarts the container, verifies task/idempotency/outbox persistence, and
exercises SQLite backup/verify/restore. It never contacts GitHub.
"""
from __future__ import annotations

import argparse
import json
import os
import secrets
import socket
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
ENV_FILE = ROOT / "deploy" / "test" / ".env.test"
COMPOSE_FILE = ROOT / "deploy" / "test" / "compose.yaml"


def free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def task_id_from(payload: dict[str, Any]) -> str:
    task = payload.get("task")
    task_id = task.get("id") if isinstance(task, dict) else None
    if not isinstance(task_id, str) or not task_id:
        raise AssertionError("Hub response did not contain a task id")
    return task_id


def lease_from(payload: dict[str, Any]) -> dict[str, Any]:
    lease = payload.get("lease")
    if not isinstance(lease, dict):
        raise AssertionError("WorkBuddy claim response did not contain a lease")
    if not isinstance(lease.get("lease_token"), str) or not isinstance(lease.get("lease_version"), int):
        raise AssertionError("WorkBuddy claim response contained an invalid lease")
    return lease


def assert_completed(payload: dict[str, Any]) -> None:
    if '"completed"' not in json.dumps(payload, ensure_ascii=False):
        raise AssertionError("Persisted task is not in completed state")


def http_json(base: str, path: str, *, method: str = "GET",
              headers: dict[str, str] | None = None,
              body: dict[str, Any] | None = None) -> dict[str, Any]:
    request_headers = dict(headers or {})
    data = None
    if body is not None:
        data = json.dumps(body, ensure_ascii=False).encode("utf-8")
        request_headers["Content-Type"] = "application/json"
    request = urllib.request.Request(base + path, data=data, headers=request_headers, method=method)
    try:
        with urllib.request.urlopen(request, timeout=10) as response:
            raw = response.read(2 * 1024 * 1024)
            if len(raw) >= 2 * 1024 * 1024:
                raise RuntimeError("Hub response exceeded the acceptance harness limit")
            parsed = json.loads(raw.decode("utf-8")) if raw else {}
            if not isinstance(parsed, dict):
                raise RuntimeError("Hub returned a non-object JSON response")
            return parsed
    except urllib.error.HTTPError as exc:
        # Deliberately do not echo response bodies, which may contain user data.
        raise RuntimeError(f"Hub API returned HTTP {exc.code} for {method} {path}") from None


def run(command: list[str], *, timeout: int = 180) -> str:
    result = subprocess.run(
        command, cwd=ROOT, text=True, stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT, timeout=timeout, check=False,
    )
    if result.returncode:
        tail = result.stdout[-5000:]
        raise RuntimeError(
            f"Command failed (exit={result.returncode}): {' '.join(command[:5])}\n{tail}"
        )
    return result.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", default=f"a2a-hub-t7-{secrets.token_hex(4)}")
    parser.add_argument("--startup-timeout", type=int, default=150)
    args = parser.parse_args()
    if not args.project.replace("-", "").replace("_", "").isalnum():
        parser.error("project must contain only letters, digits, hyphens, and underscores")
    if ENV_FILE.exists():
        raise RuntimeError(
            "Refusing to overwrite deploy/test/.env.test; move it aside and rerun"
        )

    port = free_port()
    api_token = secrets.token_urlsafe(36)
    ingress_token = secrets.token_urlsafe(36)
    connector_token = secrets.token_urlsafe(36)
    env_values = {
        "A2A_API_TOKEN": api_token,
        "A2A_TEST_PORT": str(port),
        "A2A_CHATGPT_INGRESS_TOKEN": ingress_token,
        "A2A_CHATGPT_INGRESS_ACTOR": "human:default",
        "A2A_CHATGPT_INGRESS_ALLOWED_AGENTS": "echo",
        "A2A_WORKBUDDY_CONNECTOR_TOKEN": connector_token,
        "A2A_WORKBUDDY_CONNECTOR_ALLOWED_AGENTS": "echo",
        "A2A_GITHUB_RELAY_HMAC_SECRET": "",
        "A2A_GITHUB_RELAY_API_TOKEN": "",
        "A2A_GITHUB_RELAY_ALLOWED_REPOS": "",
        "A2A_GITHUB_CALLBACK_OUTBOX_MAX_ATTEMPTS": "3",
        "A2A_GITHUB_CALLBACK_OUTBOX_POLL_SECONDS": "0.2",
    }
    ENV_FILE.write_text(
        "# generated by compose_runtime_acceptance.py; deleted on exit\n"
        + "".join(f"{key}={value}\n" for key, value in env_values.items()),
        encoding="utf-8",
    )
    compose = [
        "docker", "compose", "-p", args.project,
        "--env-file", str(ENV_FILE.relative_to(ROOT)),
        "-f", str(COMPOSE_FILE.relative_to(ROOT)),
    ]
    base = f"http://127.0.0.1:{port}"
    ingress_headers = {"X-ChatGPT-Ingress-Token": ingress_token}
    connector_headers = {"X-WorkBuddy-Connector-Token": connector_token}
    task_id = ""
    outbox_marker = "t7-runtime-outbox-persistence-marker"
    started = False
    try:
        run(compose + ["up", "-d", "--build"], timeout=600)
        started = True

        deadline = time.monotonic() + args.startup_timeout
        while time.monotonic() < deadline:
            try:
                http_json(base, "/health")
                break
            except Exception:
                time.sleep(2)
        else:
            raise RuntimeError("Hub did not become healthy before startup timeout")

        idem = "t7-runtime-" + secrets.token_hex(12)
        submit_body = {
            "agent_id": "echo",
            "prompt": "A2A Hub T7 disposable container runtime persistence acceptance",
            "mode": "pull",
        }
        submitted = http_json(
            base, "/integrations/chatgpt/v1/tasks", method="POST",
            headers={**ingress_headers, "Idempotency-Key": idem}, body=submit_body,
        )
        task_id = task_id_from(submitted)
        replay = http_json(
            base, "/integrations/chatgpt/v1/tasks", method="POST",
            headers={**ingress_headers, "Idempotency-Key": idem}, body=submit_body,
        )
        if task_id_from(replay) != task_id or replay.get("idempotent_replay") is not True:
            raise AssertionError("Ingress idempotency did not replay the original task")

        claimed = http_json(
            base, "/integrations/workbuddy/v1/claim", method="POST",
            headers=connector_headers, body={"agent_ids": ["echo"], "lease_seconds": 120},
        )
        if claimed.get("claimed") is not True or task_id_from(claimed) != task_id:
            raise AssertionError("WorkBuddy did not claim the expected Pull task")
        lease = lease_from(claimed)
        lease_body = {
            "lease_token": lease["lease_token"],
            "lease_version": lease["lease_version"],
        }
        http_json(
            base, f"/integrations/workbuddy/v1/tasks/{task_id}/start",
            method="POST", headers=connector_headers, body=lease_body,
        )
        result_body = {
            **lease_body,
            "result_key": "t7-result-" + secrets.token_hex(8),
            "state": "completed",
            "output": "T7 container runtime result persisted",
        }
        result = http_json(
            base, f"/integrations/workbuddy/v1/tasks/{task_id}/result",
            method="POST", headers=connector_headers, body=result_body,
        )
        assert_completed(result)

        # Exercise outbox DB persistence without enabling any external callback.
        create_outbox = (
            "from a2a_hub.github_callback_outbox import GithubCallbackOutbox; "
            "o=GithubCallbackOutbox('/app/data/github_callback_outbox.db'); "
            f"assert o.enqueue('{outbox_marker}', "
            "{'repository':'owner/repo','issue_number':1,'source_comment_id':1}, "
            "'completed','synthetic runtime marker'); "
            f"assert o.status('{outbox_marker}')['status']=='pending'"
        )
        run(compose + ["exec", "-T", "hub-test", "python", "-c", create_outbox])
        for db in ("a2a_hub.db", "chatgpt_ingress.db", "github_callback_outbox.db"):
            run(compose + [
                "exec", "-T", "hub-test", "python", "scripts/sqlite_maintenance.py",
                "backup", "--database", f"/app/data/{db}",
                "--output", f"/app/backups/t7-{db}",
            ])
            run(compose + [
                "exec", "-T", "hub-test", "python", "scripts/sqlite_maintenance.py",
                "verify", "--database", f"/app/backups/t7-{db}",
            ])
        run(compose + [
            "exec", "-T", "hub-test", "python", "scripts/sqlite_maintenance.py",
            "restore", "--backup", "/app/backups/t7-github_callback_outbox.db",
            "--database", "/app/backups/t7-outbox-restore-check.db",
        ])
        run(compose + [
            "exec", "-T", "hub-test", "python", "scripts/sqlite_maintenance.py",
            "verify", "--database", "/app/backups/t7-outbox-restore-check.db",
        ])

        run(compose + ["restart", "hub-test"])
        deadline = time.monotonic() + args.startup_timeout
        while time.monotonic() < deadline:
            try:
                http_json(base, "/health")
                break
            except Exception:
                time.sleep(2)
        else:
            raise RuntimeError("Hub did not recover health after container restart")

        persisted = http_json(
            base, f"/integrations/chatgpt/v1/tasks/{task_id}", headers=ingress_headers,
        )
        assert_completed(persisted)
        replay_after_restart = http_json(
            base, "/integrations/chatgpt/v1/tasks", method="POST",
            headers={**ingress_headers, "Idempotency-Key": idem}, body=submit_body,
        )
        if task_id_from(replay_after_restart) != task_id or replay_after_restart.get("idempotent_replay") is not True:
            raise AssertionError("Task idempotency did not survive container restart")
        outbox_status_code = (
            "from a2a_hub.github_callback_outbox import GithubCallbackOutbox; "
            f"o=GithubCallbackOutbox('/app/data/github_callback_outbox.db'); "
            f"assert o.status('{outbox_marker}')['status']=='pending'"
        )
        run(compose + ["exec", "-T", "hub-test", "python", "-c", outbox_status_code])
        run(compose + [
            "exec", "-T", "hub-test", "python", "scripts/sqlite_maintenance.py",
            "verify", "--database", "/app/data/a2a_hub.db",
        ])
        print(json.dumps({
            "result": "PASS",
            "task_id": task_id,
            "ingress_idempotency": "PASS",
            "workbuddy_pull_roundtrip": "PASS",
            "task_persistence_after_container_restart": "PASS",
            "outbox_persistence_after_container_restart": "PASS",
            "backup_verify_restore": "PASS",
            "real_github_credentials_used": False,
            "external_github_write_performed": False,
            "public_port_exposed": False,
        }, ensure_ascii=False))
        return 0
    finally:
        try:
            if started:
                subprocess.run(
                    compose + ["down", "-v", "--remove-orphans"],
                    cwd=ROOT, text=True, stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL, timeout=120, check=False,
                )
        finally:
            ENV_FILE.unlink(missing_ok=True)


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"T7 runtime acceptance FAILED: {type(exc).__name__}: {exc}", file=sys.stderr)
        raise SystemExit(1)
